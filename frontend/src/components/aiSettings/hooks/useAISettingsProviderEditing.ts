export const useAISettingsProviderEditing = (input: UseAISettingsProviderEditingInput) => {
  const leave = useAISettingsProviderLeave(input);
  const add = useAISettingsProviderAdd(input, leave.confirmProviderLeave);
  const edit = useAISettingsProviderEdit(input, leave.confirmProviderLeave);
  const remove = useAISettingsProviderDelete(input);
  const payload = useAISettingsProviderPayload(input);
  const save = useAISettingsProviderSave(input, payload.buildProviderPayload);
  const preferences = useAISettingsProviderPreferences(input);
  return { ...leave, ...add, ...edit, ...remove, ...payload, ...save, ...preferences };
};
export type AISettingsProviderEditingApi = ReturnType<typeof useAISettingsProviderEditing>;
